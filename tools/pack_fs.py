#!/usr/bin/env python3
"""Packs programs/ into the INPS filesystem image and generates C headers for the installer.

Usage: pack_fs.py --programs programs --boot build/boot/boot.bin --dir-sector 256 --out-dir build

Writes   <out-dir>/fs.bin, <out-dir>/fs_bin.h, <out-dir>/boot_bin.h
Layout (must match kernel/fs.h):
    sector 0  : up to 10 x 48-byte entries, signature "INPS" at byte 508
    sector 1+ : file data, each file padded to whole sectors
"""
import argparse
import os
import struct
import sys

ENTRY = struct.Struct('<32sIIIB3x')          # name, start_sector, num_sectors, size, used
MAX_FILES = 10
SECTOR = 512


def c_array(name, data):
    out = ["/* Auto-generated by tools/pack_fs.py - do not edit */",
           f"#ifndef {name.upper()}_H", f"#define {name.upper()}_H", "",
           f"static const unsigned char {name}[] = {{"]
    for i in range(0, len(data), 12):
        out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 12]) + ",")
    out += ["};", f"static const unsigned int {name}_len = {len(data)};", "#endif", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--programs', required=True)
    ap.add_argument('--boot', required=True)
    ap.add_argument('--dir-sector', type=int, default=256)
    ap.add_argument('--out-dir', required=True)
    a = ap.parse_args()

    if not os.path.isdir(a.programs):
        sys.exit(f"error: programs directory '{a.programs}' does not exist")

    files = sorted(f for f in os.listdir(a.programs) if f.endswith(('.easec', '.modec')))
    if len(files) > MAX_FILES:
        # The original silently dropped everything after the 10th file.
        sys.exit(f"error: {len(files)} program files but the INPS directory holds only {MAX_FILES}:\n  "
                 + "\n  ".join(files))

    directory = bytearray(SECTOR)
    blob = bytearray()
    next_sector = a.dir_sector + 1
    for i, name in enumerate(files):
        raw = name.encode('ascii')
        if len(raw) > 31:
            sys.exit(f"error: file name '{name}' is longer than 31 characters")
        data = open(os.path.join(a.programs, name), 'rb').read()
        nsec = max(1, (len(data) + SECTOR - 1) // SECTOR)
        directory[i * ENTRY.size:(i + 1) * ENTRY.size] = ENTRY.pack(raw, next_sector, nsec, len(data), 1)
        blob += data + b'\0' * (nsec * SECTOR - len(data))
        next_sector += nsec
    directory[508:512] = b'INPS'
    image = bytes(directory) + bytes(blob)

    os.makedirs(a.out_dir, exist_ok=True)
    open(os.path.join(a.out_dir, 'fs.bin'), 'wb').write(image)
    open(os.path.join(a.out_dir, 'fs_bin.h'), 'w').write(c_array('fs_bin', image))
    boot = open(a.boot, 'rb').read()
    if len(boot) != SECTOR:
        sys.exit(f"error: boot sector is {len(boot)} bytes, expected {SECTOR}")
    open(os.path.join(a.out_dir, 'boot_bin.h'), 'w').write(c_array('boot_bin', boot))
    print(f"Packed {len(files)} files ({len(image)} bytes) into {a.out_dir}/fs.bin")


if __name__ == '__main__':
    main()
